INSERT INTO coaches (id, trainid, coach_number, coach_type)
SELECT (t.id - 1) * 4 + c.coach_index,
       t.id,
       'T' || t.train_number || '-' || c.coach_label,
       c.coach_type
FROM trains t
CROSS JOIN (VALUES
    (1, 'A1', 'FIRST_AC'),
    (2, 'A2', 'SECOND_AC'),
    (3, 'B1', 'THIRD_AC'),
    (4, 'S1', 'SLEEPER')
) AS c(coach_index, coach_label, coach_type);

INSERT INTO seats (id, coach_id, seat_number, seat_type, seat_status)
SELECT (c.id - 1) * 24 + s.seat_number,
       c.id,
       s.seat_number::TEXT,
       CASE s.seat_number % 8
           WHEN 1 THEN 'LOWER'
           WHEN 2 THEN 'MIDDLE_BERTH'
           WHEN 3 THEN 'UPPER'
           WHEN 4 THEN 'SIDE_LOWER'
           WHEN 5 THEN 'SIDE_UPPER'
           WHEN 6 THEN 'WINDOW'
           WHEN 7 THEN 'AISLE'
           ELSE 'MIDDLE'
       END,
       CASE WHEN s.seat_number % 19 = 0 THEN 'MAINTENANCE' ELSE 'AVAILABLE' END
FROM coaches c
CROSS JOIN generate_series(1, 24) AS s(seat_number);

INSERT INTO route_stop (id, train_id, station_id, stop_sequence, arrival_time, departure_time)
SELECT (t.id - 1) * 5 + r.stop_sequence,
       t.id,
       ((t.id + r.stop_sequence - 2) % 20) + 1,
       r.stop_sequence,
       CASE WHEN r.stop_sequence = 1 THEN NULL
            ELSE TIME '05:00' + ((r.stop_sequence - 1) * INTERVAL '2 hours') END,
       CASE WHEN r.stop_sequence = 5 THEN NULL
            ELSE TIME '05:10' + ((r.stop_sequence - 1) * INTERVAL '2 hours') END
FROM trains t
CROSS JOIN generate_series(1, 5) AS r(stop_sequence);

WITH route_pairs AS (
    SELECT src.train_id,
           src.station_id AS source_station_id,
           dst.station_id AS destination_station_id,
           dst.stop_sequence - src.stop_sequence AS distance,
           coach.coach_type
    FROM route_stop src
    JOIN route_stop dst
      ON dst.train_id = src.train_id
     AND dst.stop_sequence > src.stop_sequence
    CROSS JOIN (VALUES ('FIRST_AC'), ('SECOND_AC'), ('THIRD_AC'), ('SLEEPER')) AS coach(coach_type)
)
INSERT INTO fares (id, train_id, coach_type, source_station_id, destination_station_id, fare_amount)
SELECT ROW_NUMBER() OVER (ORDER BY train_id, source_station_id, destination_station_id, coach_type),
       train_id,
       coach_type,
       source_station_id,
       destination_station_id,
       (CASE coach_type
            WHEN 'FIRST_AC' THEN 1100
            WHEN 'SECOND_AC' THEN 800
            WHEN 'THIRD_AC' THEN 550
            ELSE 280
        END + distance * 125)::NUMERIC(38, 2)
FROM route_pairs;

