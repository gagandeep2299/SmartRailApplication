CREATE TABLE IF NOT EXISTS station (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) UNIQUE,
    name VARCHAR(255),
    state VARCHAR(255),
    city VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS trains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_number VARCHAR(255) UNIQUE,
    name VARCHAR(255),
    status VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS coaches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainid BIGINT REFERENCES trains(id),
    coach_number VARCHAR(255) UNIQUE,
    coach_type VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coach_id BIGINT REFERENCES coaches(id),
    seat_number VARCHAR(255),
    seat_type VARCHAR(255),
    seat_status VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS route_stop (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT REFERENCES trains(id),
    station_id BIGINT REFERENCES station(id),
    stop_sequence BIGINT,
    arrival_time TIME,
    departure_time TIME
);

CREATE TABLE IF NOT EXISTS fares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT REFERENCES trains(id),
    coach_type VARCHAR(255),
    source_station_id BIGINT REFERENCES station(id),
    destination_station_id BIGINT REFERENCES station(id),
    fare_amount NUMERIC(38, 2)
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    train_id BIGINT REFERENCES trains(id),
    travel_date_time TIMESTAMP NOT NULL,
    booking_status VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS booking_seats (
    id BIGINT PRIMARY KEY,
    booking_id BIGINT REFERENCES booking(id),
    seat_id BIGINT REFERENCES seats(id)
);

CREATE TABLE IF NOT EXISTS payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES booking(id),
    amount NUMERIC(38, 2) NOT NULL,
    payment_status VARCHAR(255) NOT NULL,
    transaction_reference VARCHAR(255) UNIQUE
);

