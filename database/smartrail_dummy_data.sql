CREATE TABLE station (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) UNIQUE,
    name VARCHAR(255),
    state VARCHAR(255),
    city VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE trains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_number VARCHAR(255) UNIQUE,
    name VARCHAR(255),
    status VARCHAR(255)
);

CREATE TABLE coaches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainid BIGINT REFERENCES trains(id),
    coach_number VARCHAR(255) UNIQUE,
    coach_type VARCHAR(255)
);

CREATE TABLE seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coach_id BIGINT REFERENCES coaches(id),
    seat_number VARCHAR(255),
    seat_type VARCHAR(255),
    seat_status VARCHAR(255)
);

CREATE TABLE route_stop (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT REFERENCES trains(id),
    station_id BIGINT REFERENCES station(id),
    stop_sequence BIGINT,
    arrival_time TIME,
    departure_time TIME
);

CREATE TABLE fares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT REFERENCES trains(id),
    coach_type VARCHAR(255),
    source_station_id BIGINT REFERENCES station(id),
    destination_station_id BIGINT REFERENCES station(id),
    fare_amount NUMERIC(38, 2)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    source_station_id BIGINT REFERENCES station(id),
    destination_station_id BIGINT REFERENCES station(id),
    train_id BIGINT NOT NULL REFERENCES trains(id),
    travel_date DATE NOT NULL,
    booking_status VARCHAR(255) NOT NULL,
    total_price NUMERIC(38, 2) NOT NULL
);

CREATE TABLE booking_seats (
    id BIGINT PRIMARY KEY,
    booking_id BIGINT REFERENCES booking(id),
    seat_id BIGINT REFERENCES seats(id),
    booking_status VARCHAR(255) NOT NULL,
    price NUMERIC(10, 2)
);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES booking(id),
    amount NUMERIC(38, 2) NOT NULL,
    payment_status VARCHAR(255) NOT NULL,
    transaction_reference VARCHAR(255) UNIQUE
);

CREATE INDEX idx_coaches_trainid ON coaches(trainid);
CREATE INDEX idx_seats_coach_id ON seats(coach_id);
CREATE INDEX idx_route_stop_train_sequence ON route_stop(train_id, stop_sequence);
CREATE INDEX idx_fares_route ON fares(train_id, source_station_id, destination_station_id);
CREATE INDEX idx_booking_user ON booking(user_id);
CREATE INDEX idx_booking_train_date ON booking(train_id, travel_date);
CREATE INDEX idx_booking_seats_booking ON booking_seats(booking_id);
CREATE INDEX idx_payment_booking ON payment(booking_id);

